/// R_{abcd} = eta_ae R^e_bcd  (eta = diag(-1,1,1,1)) — a=0 행 부호반전.
pub fn riemann_low(p: &[f64; 24], out: &mut [f64; 256]) {
    riemann_up(p, out);
    for i in 0..64 {
        out[i] = -out[i];
    }
}

