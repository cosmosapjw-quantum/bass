"""
PR-32 · 상대론적 자유도 g_*(T), g_*s(T).

표준모형 유효 자유도.  에너지밀도 g_* 와 엔트로피 g_*s 는 e± 소멸 이후 갈라진다
(중성미자가 광자보다 차갑기 때문).

★ v3.0 (A1): 굵은 골격 표(18점)를 **격자QCD 기반 36점 표**로 교체.
  구표는 QCD 전이 구간에서 크게 틀렸다 — 예: T = 1 GeV 에서 106.75 (참값 76.34,
  **40% 과대**), T = 200 keV 에서 3.909 (참값 7.66, 2배 과소).  이 구간은 WIMP
  동결(x_f ~ m/20)이 실제로 놓이는 곳이라 잔존량에 직접 영향을 준다.
  출처: Husdal, "On Effective Degrees of Freedom in the Early Universe",
  Galaxies 4 (2016) 78, Table A1 (arXiv:1609.04979; 격자QCD 상태방정식 반영).

기준값 (오라클):
  T = 10 TeV : g_* = g_*s = 106.75   (SM 전체)
  T = 1 TeV  : g_* = 106.72          (복사보정으로 106.75 보다 약간 낮음)
  T = 1 GeV  : g_* = 76.34           (QCD 전이 아래)
  T << m_e   : g_* = 3.36, g_*s = 3.91  (광자 + 3 중성미자, 소멸 후)

★ 한계: QCD 전이(150-214 MeV)는 원논문에서도 화학퍼텐셜 없는 단순 모형이며,
  214 -> 200 MeV 사이 급변은 크로스오버의 표 표현이다.  이 구간의 g_* 는 ~5% 불확실.

★ 이 표는 `scripts/codegen_thermo_tables.py` 를 통해 Rust 코어와 공유된다
  (Python 이 단일 진리원).  표를 고치면 codegen 을 다시 돌릴 것.
"""
from __future__ import annotations

import numpy as np

# Husdal 2016 Table A1 (격자QCD 반영).  고온 -> 저온 순, T 단위 GeV.
_T_GEV = np.array([
    10000, 5000, 2000, 1000, 500, 200, 100, 50, 20, 10,
    5, 2, 1, 0.5, 0.214, 0.2, 0.19, 0.18, 0.17, 0.16,
    0.15, 0.14, 0.13, 0.1, 0.05, 0.02, 0.01, 0.005, 0.002, 0.001,
    0.0005, 0.0002, 0.0001, 5e-05, 2e-05, 1e-05,
])
_GSTAR = np.array([
    106.75, 106.75, 106.74, 106.72, 106.61, 105.9, 103.53, 97.4, 88.45, 86.22,
    85.6, 82.5, 76.34, 69.26, 62.49, 50.75, 44.01, 38.27, 33.47, 29.51,
    26.31, 23.77, 21.76, 18.0, 14.63, 11.33, 10.76, 10.74, 10.71, 10.6,
    10.16, 7.66, 4.46, 3.39, 3.36, 3.36,
])
_GSTAR_S = np.array([
    106.75, 106.75, 106.74, 106.7, 106.56, 105.61, 102.85, 96.53, 88.14, 86.13,
    85.37, 81.8, 75.5, 68.55, 62.25, 45.47, 39.77, 34.91, 30.84, 27.49,
    24.77, 22.59, 20.86, 17.55, 14.32, 11.25, 10.76, 10.74, 10.7, 10.56,
    10.03, 7.55, 4.78, 3.93, 3.91, 3.91,
])

# 보간을 위해 오름차순(저온->고온)으로 뒤집기
_x = np.log10(_T_GEV[::-1])
_gs = _GSTAR[::-1]
_gss = _GSTAR_S[::-1]


def g_star(T_GeV):
    """유효 에너지밀도 자유도 g_*(T).  로그-선형 단조 보간, 경계는 상수 외삽."""
    x = np.log10(np.asarray(T_GeV, float))
    return np.interp(x, _x, _gs, left=_gs[0], right=_gs[-1])


def g_star_s(T_GeV):
    """유효 엔트로피 자유도 g_*s(T)."""
    x = np.log10(np.asarray(T_GeV, float))
    return np.interp(x, _x, _gss, left=_gss[0], right=_gss[-1])


def g_star_high():
    """T >> m_t 극한 g_* = 106.75 (SM)."""
    return 106.75


def g_star_low():
    """T << m_e 극한 (g_*, g_*s) = (3.363, 3.909)."""
    return 3.363, 3.909
