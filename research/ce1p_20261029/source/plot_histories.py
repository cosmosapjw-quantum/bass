#!/usr/bin/env python3
"""Read the saved CE1-P physical histories, no science rerun."""
from pathlib import Path
import csv,json
import numpy as np
import matplotlib.pyplot as plt
root=Path(__file__).resolve().parents[1]
fig=root/'figures';fig.mkdir(exist_ok=True)

def rows(fname):
    with (root/'data'/fname).open() as f:
        return [{k:float(v) for k,v in r.items() if k!='channel' and v!=''} for r in csv.DictReader(f)]

r=rows('continuum_GL40_history.csv')
u=np.array([a['u'] for a in r]);
for prefix,keys,ylabel,name,caption in [
    ('H',('h1','h2','h3'),r'$h_i = T_* H_i$', 'directional_expansion.png', 'Directional expansion of numerical GL40 continuum reference'),
    ('pi',('pi1','pi2','pi3'),r'$\pi_i = P_i - E/3$', 'anisotropic_pressure.png', 'Trace-free radiation pressure generated by the fixed six-cell source'),
    ('z',('energy_ratio_x','energy_ratio_y','energy_ratio_z'),r'$\mathcal{E}_i(u)/\mathcal{E}_i(0)=e^{-\ell_i}$', 'principal_photon_redshift.png', 'Principal null-geodesic energy ratios; not CMB temperature')]:
    fig_obj,ax=plt.subplots(figsize=(6.2,3.7))
    for key in keys:
        ax.plot(u,[a[key] for a in r],label=key.replace('energy_ratio_','ray '))
    ax.set_xlabel(r'$u=t/T_*$');ax.set_ylabel(ylabel)
    ax.grid(alpha=.3);ax.legend(fontsize=9,frameon=False,ncol=3,loc='best');
    fig_obj.tight_layout()
    fig_obj.savefig(fig/name,dpi=180,bbox_inches='tight')
    plt.close(fig_obj)

j=json.loads((root/'data'/'results.json').read_text())
q=[(1,4,8,16),[next(z for z in j['summary'] if z['channel']=='stored_ref'+str(n))['max_source_h_gap_vs_GL_reference'] for n in (1,4,8,16)]]
fig_obj,ax=plt.subplots(figsize=(6.2,3.7))
ax.loglog(q[0],q[1],'-o',label=r'Measured $\max_{u,i}|h_i^{(f)}-h_i^{\rm GL40}|$')
ax.set_xlabel('Angular cell refinement $f$');ax.set_ylabel('Max directional-expansion difference')
ax.set_xticks(q[0],['1','4','8','16'])
ax.grid(alpha=.3,which='both');ax.legend(frameon=False,fontsize=8.4)
fig_obj.tight_layout();fig_obj.savefig(fig/'angular_refinement_difference.png',dpi=180,bbox_inches='tight');plt.close(fig_obj)
print('figures:',[p.name for p in fig.glob('*.png')])