#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")" && pwd)"
TMP="${1:-$ROOT/materialized}"
test ! -e "$TMP" || { echo "STOP: target exists: $TMP" >&2; exit 1; }

cd "$ROOT"
sha256sum -c MANIFEST.sha256
cd archive
sha256sum -c PARTS.sha256
cat \
  BASS_POST_SEAL_AUDIT_COMPILED_EXEC_PLAN_V3_20260826.zip.part000 \
  BASS_POST_SEAL_AUDIT_COMPILED_EXEC_PLAN_V3_20260826.zip.part001 \
  BASS_POST_SEAL_AUDIT_COMPILED_EXEC_PLAN_V3_20260826.zip.part002 \
  BASS_POST_SEAL_AUDIT_COMPILED_EXEC_PLAN_V3_20260826.zip.part003 \
  BASS_POST_SEAL_AUDIT_COMPILED_EXEC_PLAN_V3_20260826.zip.part004 \
  BASS_POST_SEAL_AUDIT_COMPILED_EXEC_PLAN_V3_20260826.zip.part005.sub00 \
  BASS_POST_SEAL_AUDIT_COMPILED_EXEC_PLAN_V3_20260826.zip.part005.sub01 \
  BASS_POST_SEAL_AUDIT_COMPILED_EXEC_PLAN_V3_20260826.zip.part006.sub00 \
  BASS_POST_SEAL_AUDIT_COMPILED_EXEC_PLAN_V3_20260826.zip.part006.sub01 \
  BASS_POST_SEAL_AUDIT_COMPILED_EXEC_PLAN_V3_20260826.zip.part007.sub00 \
  BASS_POST_SEAL_AUDIT_COMPILED_EXEC_PLAN_V3_20260826.zip.part007.sub01 \
  > ../BASS_POST_SEAL_AUDIT_COMPILED_EXEC_PLAN_V3_20260826.zip
cd ..
sha256sum -c BASS_POST_SEAL_AUDIT_COMPILED_EXEC_PLAN_V3_20260826.zip.sha256
mkdir -p "$TMP"
unzip -q BASS_POST_SEAL_AUDIT_COMPILED_EXEC_PLAN_V3_20260826.zip -d "$TMP"
rm -f BASS_POST_SEAL_AUDIT_COMPILED_EXEC_PLAN_V3_20260826.zip
PLAN="$TMP/BASS_POST_SEAL_AUDIT_COMPILED_EXEC_PLAN_V3_20260826"
cd "$PLAN"
sha256sum -c MANIFEST.sha256
PYTHONDONTWRITEBYTECODE=1 python3 scripts/verify_compiled_package.py .
PYTHONDONTWRITEBYTECODE=1 python3 -m unittest tests.test_compiled_package -v
printf '%s\n' BASS_POST_SEAL_AUDIT_COMPILED_PLAN_V3_MATERIALIZE_PASS
